import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { PrismaService } = require('../apps/api/dist/prisma.service.js');
const { SiteCatalogService } = require('../apps/api/dist/site-catalog.service.js');
const { PublicationWorkflowService } = require('../apps/api/dist/publication-workflow.service.js');
const { AdminPageTemplatesController } = require('../apps/api/dist/admin-page-templates.controller.js');
const { cityHomeFromTemplate } = require('../apps/api/dist/city-home-view.js');
const { sitePublicDisplayDefaults } = require('../apps/api/dist/site-public-display.js');
const migration = readFileSync(new URL('../prisma/migrations/0062_city_home_composition/migration.sql', import.meta.url), 'utf8');
const container = `astro-city-home-${randomUUID().slice(0, 8)}`;
const email = 'city-home-rehearsal@example.test';
const json = value => JSON.parse(JSON.stringify(value));
const docker = (args, options = {}) => spawnSync('docker', args, { encoding: 'utf8', timeout: 120000, windowsHide: true, ...options });
const checked = result => { assert.equal(result.status, 0, result.stderr || result.stdout || result.error?.message); return result.stdout.trim(); };
const apply = () => docker(['exec', '-i', container, 'psql', '-U', 'postgres', '-d', 'provider', '-v', 'ON_ERROR_STOP=1'], { input: migration });
let db, owned = false;
try {
  checked(docker(['run', '--rm', '-d', '--name', container, '-p', '127.0.0.1::5432', '-e', 'POSTGRES_PASSWORD=postgres', '-e', 'POSTGRES_DB=provider', 'postgres:18.6-alpine']));
  owned = true;
  let ready = false;
  for (let attempt = 0; attempt < 60; attempt++) {
    if (docker(['exec', container, 'pg_isready', '-U', 'postgres', '-d', 'provider'], { timeout: 5000 }).status === 0) { ready = true; break; }
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 200);
  }
  assert.ok(ready, 'owned isolated PostgreSQL is ready');
  const port = checked(docker(['port', container, '5432/tcp'])).match(/:(\d+)\s*$/)[1];
  process.env.DATABASE_URL = `postgresql://postgres:postgres@127.0.0.1:${port}/provider`;
  checked(spawnSync('pnpm', ['--filter', '@provider/database', 'migrate:deploy'], { shell: process.platform === 'win32', env: process.env, encoding: 'utf8', timeout: 120000, windowsHide: true }));
  checked(spawnSync(process.execPath, ['apps/api/dist/seed.js'], { env: { ...process.env, ADMIN_EMAIL: email, ADMIN_PASSWORD: 'synthetic-city-home-rehearsal-password' }, encoding: 'utf8', timeout: 30000, windowsHide: true }));
  db = new PrismaService(); await db.onModuleInit();
  const template = id => db.pageTemplate.findUniqueOrThrow({ where: { id }, include: { blocks: { orderBy: { position: 'asc' } } } });
  const site = await db.site.findUniqueOrThrow({ where: { slug: 'domru-site' } });
  const fresh = await db.pageTemplate.findUniqueOrThrow({ where: { siteId_kind: { siteId: site.id, kind: 'CITY_HOME' } }, include: { blocks: { orderBy: { position: 'asc' } } } });
  assert.equal(cityHomeFromTemplate(fresh).blocks.length, 10, 'new bootstrap owns v3 directly');
  const hero = fresh.blocks[0], catalog = fresh.blocks[1];
  hero.data = { ...hero.data, title: 'Сохранённый первый экран в {CITY_NAME_PREPOSITIONAL}' };
  catalog.data = { ...catalog.data, title: 'Сохранённый каталог', initialCount: 9, sort: 'PRICE_DESC' };
  const legacyContent = { ...fresh.content, homeCompositionVersion: '2.0.0' }; delete legacyContent.cityHomeImplementationVersion;
  await db.pageTemplateBlock.deleteMany({ where: { templateId: fresh.id, blockType: { notIn: ['hero', 'tariff_grid'] } } });
  await db.pageTemplateBlock.update({ where: { id: hero.id }, data: { data: hero.data } });
  await db.pageTemplateBlock.update({ where: { id: catalog.id }, data: { data: catalog.data, position: 30 } });
  const historical = await db.pageTemplateBlock.create({ data: { templateId: fresh.id, blockType: 'faq', position: 70, visible: false, data: { title: 'Прежний скрытый FAQ', items: [] }, source: 'preserved-test-source' } });
  await db.pageTemplate.update({ where: { id: fresh.id }, data: { content: legacyContent } });
  const settings = { ...site.settings, content: { retained: 'Существующий контент' } }; delete settings.publicDisplay;
  const home = await db.pageTemplate.findUniqueOrThrow({ where: { siteId_kind: { siteId: site.id, kind: 'HOME' } }, include: { blocks: true } });
  const homeBenefits = home.blocks.find(block => block.blockType === 'home.benefits');
  const ownerBenefits = structuredClone(homeBenefits.data);
  const ownerFacts = { technologyFact: 'Владельческое описание сети', wifiFact: 'Владельческое описание Wi-Fi', movixFact: 'Владельческое описание Movix', applicationFact: 'Владельческая подпись заявки' };
  for (const [key, field] of Object.entries({ fiber: 'technologyFact', wifi6: 'wifiFact', movix: 'movixFact', connection: 'applicationFact' })) ownerBenefits.items[key].factText = ownerFacts[field];
  ownerBenefits.items.speed.factText = ''; ownerBenefits.items.support.factText = '';
  await db.pageTemplateBlock.update({ where: { id: homeBenefits.id }, data: { data: ownerBenefits } });
  await db.site.update({ where: { id: site.id }, data: { settings, workingRevision: 7, publishedRevision: 7 } });
  const published = json(await db.sitePublication.create({ data: { siteId: site.id, siteRevision: 7, status: 'SUCCEEDED', catalog: { sentinel: 'immutable-city-publication' }, triggerEntity: 'test', triggerEntityId: site.id } }));
  const foreignProvider = await db.provider.create({ data: { name: 'Другой провайдер', slug: 'city-home-other-provider' } });
  const foreign = json(await db.site.create({ data: { providerId: foreignProvider.id, name: 'Другой сайт', slug: 'city-home-other-site', settings: { private: 'retained' }, workingRevision: 3 } }));
  checked(apply());
  let current = await template(fresh.id);
  assert.equal(cityHomeFromTemplate(current).blocks.length, 10);
  const migratedSite = await db.site.findUniqueOrThrow({ where: { id: site.id } });
  assert.equal(migratedSite.workingRevision, 8); assert.equal(migratedSite.publishedRevision, 7);
  assert.deepEqual(migratedSite.settings, { ...settings, publicDisplay: { ...sitePublicDisplayDefaults(), ...ownerFacts } });
  const retainedBenefits = (await template(home.id)).blocks.find(block => block.id === homeBenefits.id);
  const expectedBenefits = structuredClone(ownerBenefits);
  expectedBenefits.items.speed.factText = 'До 1 Гбит/с'; expectedBenefits.items.support.factText = 'Круглосуточно';
  assert.deepEqual(retainedBenefits.data, expectedBenefits, 'owner titles/descriptions and four facts survive, readonly empty copies get system values');
  assert.deepEqual(current.blocks.find(block => block.id === hero.id).data, hero.data);
  assert.deepEqual(current.blocks.find(block => block.id === catalog.id).data, catalog.data);
  assert.equal(current.blocks.find(block => block.id === catalog.id).position, 20);
  const hidden = current.blocks.find(block => block.id === historical.id);
  assert.ok(hidden.position >= 1000); assert.equal(hidden.visible, false); assert.deepEqual(hidden.data, historical.data); assert.equal(hidden.source, historical.source);
  assert.deepEqual(json(await db.sitePublication.findUniqueOrThrow({ where: { id: published.id } })), published);
  assert.deepEqual(json(await db.site.findUniqueOrThrow({ where: { id: foreign.id } })), foreign);
  const stable = json(current), stableSite = json(migratedSite);
  checked(apply());
  assert.deepEqual(json(await template(fresh.id)), stable); assert.deepEqual(json(await db.site.findUniqueOrThrow({ where: { id: site.id } })), stableSite);
  const user = await db.user.findUniqueOrThrow({ where: { email } });
  const controller = new AdminPageTemplatesController(db, new PublicationWorkflowService(db, new SiteCatalogService(db)));
  const blocks = cityHomeFromTemplate(current).blocks.map(({ blockType, data }) => ({ blockType, data }));
  blocks[3].data.title = 'Сохранённая помощь';
  const saved = await controller.updateCityHomeComposition(site.id, { expectedWorkingRevision: 8, blocks }, { user: { id: user.id } });
  assert.equal(saved.workingRevision, 9);
  assert.equal((await db.auditEvent.findFirstOrThrow({ where: { siteId: site.id, source: 'admin:city-home' } })).actorId, user.id);
  current = await template(fresh.id);
  const savedStable = json(current);
  await db.$executeRawUnsafe(`ALTER TABLE "PageTemplateBlock" ADD CONSTRAINT "city_rehearsal_late_failure" CHECK ("blockType" <> 'city.contacts' OR "data"->>'title' <> 'FORCED_ROLLBACK')`);
  const rejected = structuredClone(blocks); rejected[3].data.title = 'Должно откатиться'; rejected[9].data.title = 'FORCED_ROLLBACK';
  await assert.rejects(controller.updateCityHomeComposition(site.id, { expectedWorkingRevision: 9, blocks: rejected }, { user: { id: user.id } }));
  assert.deepEqual(json(await template(fresh.id)), savedStable);
  assert.equal((await db.site.findUniqueOrThrow({ where: { id: site.id } })).workingRevision, 9);
  assert.equal(await db.contentRevision.count({ where: { siteId: site.id, source: 'admin:city-home' } }), 1);
  await db.$executeRawUnsafe('ALTER TABLE "PageTemplateBlock" DROP CONSTRAINT "city_rehearsal_late_failure"');
  await assert.rejects(controller.updateCityHomeComposition(site.id, { expectedWorkingRevision: 8, blocks }), error => error.getStatus() === 409);
  checked(apply());
  assert.deepEqual(json(await template(fresh.id)), savedStable);
  assert.equal((await db.site.findUniqueOrThrow({ where: { id: site.id } })).workingRevision, 9);
  assert.deepEqual(json(await db.sitePublication.findUniqueOrThrow({ where: { id: published.id } })), published);
  await db.pageTemplate.update({ where: { id: fresh.id }, data: { content: { ...current.content, homeCompositionVersion: '99.0.0' } } });
  assert.notEqual(apply().status, 0, 'unknown working version stops migration atomically');
  assert.equal((await db.site.findUniqueOrThrow({ where: { id: site.id } })).workingRevision, 9);
  process.stdout.write('CITY_HOME: migration, idempotence, preserved Hero/catalog, immutable publication, provider isolation and atomic save passed\n');
} finally {
  if (db) await db.onModuleDestroy();
  if (owned) docker(['rm', '-f', container]);
}
