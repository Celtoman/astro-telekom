SELECT t."id",c."siteId",t."attributes" AS before,to_jsonb(t) AS before_snapshot,
 CASE WHEN (t."attributes"->>'tvbox_buyout_price')::numeric>0 OR ((t."attributes"->>'tvbox_installment_price')::numeric>0 AND (t."attributes"->>'tvbox_installment_months')::numeric>0)
 THEN t."attributes"||'{"tvbox_available":true}'::jsonb
 ELSE (t."attributes"-'tvbox_buyout_price'-'tvbox_installment_price'-'tvbox_installment_months')||'{"tvbox_available":false}'::jsonb END AS after,
 COALESCE(a.reason,'existing-paid-offer') AS reason
FROM "Tariff" t JOIN "City" c ON c."id"=t."cityId" JOIN "Provider" p ON p."id"=t."providerId" LEFT JOIN _tvbox_absent a ON a.id=t."id"
